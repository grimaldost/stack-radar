# A transcript's own clock. Records are appended in order, so the first timestamp in the
# head and the last in the tail bound the session without parsing the middle.
TS_RE = re.compile(r'"timestamp"\s*:\s*"([^"]+)"')
EDGE = 1 << 16  # bytes read from each end when bounding a transcript in time


def _decode(buf: bytes) -> str:
    return buf.decode("utf-8", errors="replace")


def head_clock(path: Path) -> tuple[dt.datetime | None, dt.datetime | None]:
    """(the FIRST record's timestamp, the EARLIEST timestamp) from one bounded head read.

    They are not the same, and reading them as one puts the retention horizon too late.
    Records are appended in order, so the first timestamp is where the session began -
    which is what the census wants, because that is the session's own clock. But a
    resumed or forked session REPLAYS the session it continues, and the replayed records keep
    their original, earlier timestamps while sitting after the resume header. So the
    earliest timestamp in the file can predate the first one.

    The second element is the earliest timestamp in the head: it costs nothing (the
    bytes are already read) and it reaches back through any replay that fits in the
    head. It is still a bounded read, so it is a CEILING on how far back the evidence
    goes rather than the edge itself - a replay deeper than 64 KiB into a file is not
    seen - and both the finding and the JSON field name say so rather than implying a
    measurement.
    """
    try:
        with path.open("rb") as fh:
            found = TS_RE.findall(_decode(fh.read(EDGE)))
    except OSError:
        return None, None
    if not found:
        return None, None
    stamps = [ts for ts in (parse_ts(s) for s in found) if ts is not None]
    return (parse_ts(found[0]), min(stamps) if stamps else None)


def last_timestamp(path: Path) -> dt.datetime | None:
    """The latest record's timestamp, from a bounded read of the file's tail.

    Bounded on purpose: a transcript can grow large, and the census has to stay cheap
    enough to run over every one of them on every scheduled review. A 64 KiB tail
    holds many whole records; if it somehow held none, the caller falls back to mtime.
    """
    try:
        with path.open("rb") as fh:
            size = fh.seek(0, 2)
            fh.seek(max(0, size - EDGE))
            found = TS_RE.findall(_decode(fh.read()))
    except OSError:
        return None
    return parse_ts(found[-1]) if found else None


class Transcript:
    """One transcript file with everything the census needs to place it in time."""

    __slots__ = ("path", "session", "slug", "subagent", "mtime", "first", "last", "scan")

    def __init__(self, path, session, slug, subagent, mtime):
        self.path = path
        self.session = session
        self.slug = slug
        self.subagent = subagent
        self.mtime = mtime  # dt.date, UTC
        self.first: dt.datetime | None = None
        self.last: dt.datetime | None = None
        self.scan = False

    @property
    def order(self) -> tuple:
        """Oldest-first key. The file's own clock where it has one, else its mtime."""
        return (self.first.isoformat() if self.first else self.mtime.isoformat(), str(self.path))


class Index:
    """The transcript census for one window, computed once and shared across tools.

    WHY NOT MTIME: a transcript's mtime is not its content's age. A client can rewrite
    transcript mtimes - opening or displaying a transcript can move its mtime to around
    the present. Were a session in the window when its main transcript's mtime fell
    inside it, old sessions touched that way would enter a later window's denominator and
    inflate the "used in N of M sessions" ratio that decides a pilot. So a session is in
    the window when its own record interval overlaps it: record timestamps are written
    once, when the record is, and nothing rewrites them.

    mtime survives as a PRE-FILTER only, and only in the direction where it cannot lie:
    a file's mtime can be later than its content (a rewrite, a copy, a backup restore)
    but never earlier, so `mtime < since` really does mean "no record inside the window".
    """

    def __init__(self, files, since: dt.date, until: dt.date) -> None:
        self.since, self.until = since, until
        self.transcripts: list[Transcript] = []
        self.sessions: set[str] = set()
        # TRANSCRIPTS, not sessions - the loop below runs once per FILE, so the name says
        # transcripts. The count is of main transcripts whose mtime falls
        # in the window while their own records do not, which is a different quantity from
        # the sessions those files stand for: a session with a second, in-window transcript
        # is not excluded from the census by one of its files being. Naming a file count
        # after sessions invites subtracting it from the denominator, which would be wrong.
        self.transcripts_excluded_by_timestamp = 0
        self.dated_by_mtime = 0
        # A CEILING on how far back the evidence reaches, not the edge - see head_clock.
        self.oldest_record_by_head_scan: dt.date | None = None

        for path, session_id, slug, subagent in files:
            try:
                mtime = utc_date(path.stat().st_mtime)
            except OSError:
                continue
            t = Transcript(path, session_id, slug, subagent, mtime)
            if subagent:
                # Sidechains are not sessions and never enter the denominator, so they
                # are not worth two extra reads each: the mtime pre-filter is enough.
                t.scan = mtime >= since
                if t.scan:
                    self.transcripts.append(t)
                continue

            # Read the head even for files the pre-filter would drop: the retention
            # check needs the oldest record that exists ON DISK, and that is by
            # definition in a file older than the window.
            t.first, earliest = head_clock(path)
            # The census keeps the FIRST record (the session's own start); the retention
            # horizon takes the EARLIEST in the head, which a replayed history can push
            # back. Deliberately not the same value: feeding a replayed, older timestamp
            # into a later session's overlap test would put that session into an older
            # window's denominator, which is the mtime-inflation defect wearing a new hat.
            if earliest and (
                self.oldest_record_by_head_scan is None
                or earliest.date() < self.oldest_record_by_head_scan
            ):
                self.oldest_record_by_head_scan = earliest.date()
            if mtime < since:
                continue
            t.last = last_timestamp(path)

            by_mtime = since <= mtime <= until
            if t.first and t.last:
                overlaps = t.first.date() <= until and t.last.date() >= since
            else:
                # No parseable timestamp at either end: fall back to the mtime rule rather
                # than silently dropping the session out of the denominator.
                overlaps = by_mtime
                self.dated_by_mtime += 1
            if overlaps:
                self.sessions.add(session_id)
            elif by_mtime:
                self.transcripts_excluded_by_timestamp += 1
            # A file whose own interval misses the window holds no in-window record, so
            # it is not worth streaming either.
            t.scan = overlaps
            if t.scan:
                self.transcripts.append(t)

        self.transcripts.sort(key=lambda t: t.order)


# --------------------------------------------------------- reconciliation (drift)

# TWO PARSERS FOR ONE FACT. A second invocation table can be derived by another parser
# from the same .jsonl files this script reads, with the same question in mind: which
# tool did this call invoke. Two implementations of one fact drift silently, and the
# drift is invisible precisely because each is confident on its own. So the duplication
# is turned into an instrument: --reconcile counts the table's rows under this entry's
# matchers and reports the disagreement per matcher kind.
#
# What it is NOT: a source of truth. The table is a snapshot with a generation time, so
# both sides are counted only up to that time - a call made after it cannot be in the
# table - and its age is printed with the counts.
#
# The input is invocation table format, version 1, specified in docs/concepts.md
# ("Cross-checking against an invocation table"): `derived/invocations.jsonl` (one row
# per call, with `timestamp`, `tool`, `exe`, `skill` and `first_seen`) and
# `derived/derive.json` (`generated_at`, and optionally `format`, which is accepted and
# not acted on), under the profile's `[paths].transcript_index`. Anything that writes
# those two files can be cross-checked.
#
# SCRIPT NAMES. command_identities() names the script an interpreter runs, so a
# script-named glob is compared like any other. A table that records only the
# interpreter reads as drift on such a glob, which is the right signal: excusing it
# would hide exactly the disagreement this check exists to surface.
RECONCILE_KINDS = ("command", "skill", "mcp")
_INDEX_CACHE: dict[str, tuple[list[tuple], str | None]] = {}


def load_transcript_index(store: Path) -> tuple[list[tuple], str | None] | None:
    """(rows, generated_at) from an invocation table (format version 1) under `store`,
    or None if absent.

    Cached per store path: --all reconciles every entry against the same table, which
    can be large, and reading it once per tool would dominate the run.

    Only `first_seen` rows are kept - the table marks replayed copies, and counting
    them would compare our de-duplicated numbers against its raw ones and report drift
    that is really just the two sides answering different questions.
    """
    key = str(store)
    if key in _INDEX_CACHE:
        return _INDEX_CACHE[key]
    table = store / "derived" / "invocations.jsonl"
    if not table.is_file():
        return None
    generated_at = None
    meta = store / "derived" / "derive.json"
    if meta.is_file():
        try:
            generated_at = json.loads(meta.read_text(encoding="utf-8")).get("generated_at")
        except (OSError, ValueError):
            generated_at = None
    rows: list[tuple] = []
    with table.open(encoding="utf-8", errors="replace") as fh:
        for line in fh:
            try:
                r = json.loads(line)
            except ValueError:
                continue
            if not r.get("first_seen"):
                continue
            ts = r.get("timestamp")
            if not isinstance(ts, str):
                continue
            exe = r.get("exe")
            rows.append(
                (
                    ts[:10],
                    utc_moment(ts),
                    r.get("tool") or "",
                    tuple(e for e in exe if isinstance(e, str)) if isinstance(exe, list) else (),
                    r.get("skill") if isinstance(r.get("skill"), str) else None,
                )
            )
    _INDEX_CACHE[key] = (rows, generated_at)
    return _INDEX_CACHE[key]


def index_counts(
    rows: list[tuple],
    since: dt.date,
    until: dt.date,
    globs: list[str],
    skill_globs: list[str],
    command_globs: list[str],
    cutoff: dt.datetime | None = None,
) -> dict[str, int]:
    """The index's count under each matcher kind, over the same window.

    `cutoff` is the index's own generation time: a record after it cannot be in the
    index, so neither side counts one (see `our_counts`).
    """
    lo, hi = since.isoformat(), until.isoformat()
    out = dict.fromkeys(RECONCILE_KINDS, 0)
    for day, moment, tool_name, exe, skill in rows:
        if not (lo <= day <= hi):
            continue
        if cutoff is not None and moment is not None and moment > cutoff:
            continue
        if command_globs and any(matches(e, command_globs) for e in exe):
            out["command"] += 1
        if skill_globs and skill and matches(skill, skill_globs):
            out["skill"] += 1
        if globs and matches(tool_name, globs):
            out["mcp"] += 1
    return out


def our_counts(
    in_window: list[dict],
    command_globs: list[str] | None = None,
    cutoff: dt.datetime | None = None,
) -> dict[str, int]:
    """The same three counts from this run, keyed the same way.

    `command_globs` narrows the `command` count to the identities those globs match, so
    the comparison can be run over only the globs the index can express. None
    means "count every cmd: row", which is what a report with nothing excluded wants.

    `cutoff` stops the count at the index's generation time. The transcripts keep
    growing after the index is derived, so counting the whole window would report every
    call made since then as a disagreement between the scanners.
    """
    out = dict.fromkeys(RECONCILE_KINDS, 0)
    for i in in_window:
        if cutoff is not None:
            moment = utc_moment(i.get("at"))
            if moment is not None and moment > cutoff:
                continue
        name = i["tool"]
        if name.startswith("cmd:"):
            if command_globs is not None and not matches(name[4:], command_globs):
                continue
            out["command"] += 1
        elif name.startswith("skill:"):
            out["skill"] += 1
        else:
            out["mcp"] += 1
    return out


def reconcile_lines(tool_name: str, rec: dict | None) -> list[str]:
    """The agreement read-out, one line per matcher kind. Console form."""
    if not rec:
        return []
    age = f", derived {rec['age_hours']}h ago" if rec.get("age_hours") is not None else ""
    out = [
        f"reconcile {tool_name} vs invocation table ({rec['generated_at'] or 'unknown date'}{age}):"
    ]
    if not rec["kinds"]:
        return out + ["  (no comparable matcher kind on this entry)"]
    for k in rec["kinds"]:
        verdict = "agree" if k["relative"] <= rec["tolerance"] else "DRIFT"
        out.append(
            f"  {k['kind']:<8} ours {k['ours']:>6}  index {k['index']:>6}  "
            f"delta {k['delta']:+d} ({k['relative']:.1%}) {verdict}"
        )
    return out


def utc_moment(raw: str | None) -> dt.datetime | None:
    """A timestamp as an aware UTC datetime; one written without a zone is read as UTC."""
    ts = parse_ts(raw)
    if ts is None:
        return None
    return ts.replace(tzinfo=dt.UTC) if ts.tzinfo is None else ts.astimezone(dt.UTC)


def derive_age_hours(generated_at: str | None) -> float | None:
    """How old the index is, in hours. In days, an index derived this morning read as
    "0d ago" however many calls had been made since."""
    ts = utc_moment(generated_at)
    if ts is None:
        return None
    return round((dt.datetime.now(dt.UTC) - ts).total_seconds() / 3600, 1)


# ------------------------------------------------------------------------ statistics


def pct(values: list[float], q: float) -> float | None:
    if not values:
        return None
    if len(values) == 1:
        return round(values[0], 1)
    s = sorted(values)
    idx = max(0, min(len(s) - 1, int(-(-len(s) * q // 1)) - 1))
    return round(s[idx], 1)


def med(values: list[float]) -> float | None:
    return round(statistics.median(values), 1) if values else None


def utc_date(epoch: float) -> dt.date:
    return dt.datetime.fromtimestamp(epoch, dt.UTC).date()


