"""Passive field telemetry for a pilot-ring tool, mined post-hoc from transcripts.

Why post-hoc: a pilot must cost nothing to observe. Hooks, prompts, wrappers and
agent cooperation all tax every working session and change the thing being measured.
Claude Code already writes a complete tool-call log to disk, so the honest cheap
option is to read it afterwards. Consequence: this script is retroactive by nature
and adds zero burden — and it can be pointed at a window that predates the decision
to measure.

What the numbers are NOT: causal. There is no control arm here, no counterfactual,
no randomisation. Field telemetry answers "was there ever an opportunity, and did the
tool get used on it" — the opportunity-frequency census that actually decides a
small-effect tool. It cannot answer "did it help". A controlled evaluation answers that.

Reads the data plane (transcripts) read-only and writes only into the radar's own
`field/` directory, so the control-plane invariant holds: nothing is
written into the stack, and the stack is not made aware that the radar exists.
"""

