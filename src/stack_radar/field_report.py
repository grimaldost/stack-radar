def literal_prefix(glob: str) -> str:
    """The fixed head of a glob — the part usable as a raw-bytes prescan needle."""
    for i, ch in enumerate(glob):
        if ch in GLOB_META:
            return glob[:i]
    return glob


def matches(name: str, globs: list[str]) -> bool:
    return any(fnmatch(name, g) for g in globs)


def expand_command_globs(globs: list[str]) -> list[str]:
    """The declared command globs, plus the module spelling of each literal one.

    A DISTRIBUTION NAME IS NOT A MODULE NAME, and cmdscan reports the module. It
    resolves `python -m pre_commit` to "pre_commit" because that is what the
    interpreter was told to run, while the radar names the tool the way it is
    installed and published - `pre-commit`. Python packaging turns the hyphen into an
    underscore on import, so an entry written correctly could not match the module
    invocation form.

    That form is not a rarity: where a machine refuses unsigned console-script shims
    (docs/new-environment.md, "Unsigned executables"), `python -m pre_commit` is the only
    way the tool runs, and an entry that matched only the distribution name would report
    a fraction of the real invocations.

    Expanding here rather than adding a second glob to each hyphenated entry: the
    equivalence is a property of Python packaging, not a judgement about one tool, and
    the next hyphenated entry cannot be relied on to remember it. The expansion is inert
    unless the module form is actually invoked.

    Only a LITERAL glob is respelled. In a pattern the hyphen may be structural - in a
    character class it is a range, and `[a-c]` respelled is the set {a, _, c} - so a
    pattern is left exactly as its author wrote it.
    """
    out = list(globs)
    for g in globs:
        if "-" not in g or any(ch in g for ch in GLOB_META):
            continue
        alt = g.replace("-", "_")
        if alt not in out:
            out.append(alt)
    return out


# Tool names that carry a shell command line. Both exist in transcripts.
BASH_TOOLS = ("Bash", "PowerShell")


class Matchers(NamedTuple):
    """One matcher set: the three ways a tool can appear in a transcript.

    Two of these exist per run - the entry's own matchers (did the tool get used) and its
    opportunity matchers (was there an occasion where it would have applied). Bundled
    rather than passed as six positional lists because the scan needs BOTH and a
    nine-argument scan_file was already at the limit of what a reader can hold.
    """

    tool: list[str]  # MCP tool-name globs
    skill: list[str]  # globs over a Skill call's input.skill
    command: list[str]  # globs over a shell command's RESOLVED chain

    def declared(self) -> bool:
        return bool(self.tool or self.skill or self.command)


EMPTY = Matchers([], [], [])


def matched_name(block: dict, name: str, m: Matchers) -> str | None:
    """What this tool_use should be REPORTED as under `m`, or None if it does not match.

    The precedence is deliberate and load-bearing. A skill invocation reaches the
    transcript as tool_use name="Skill" with the skill id in `input.skill`, so an own-ring
    tool - reached through its skills rather than through MCP tools - is only visible by
    matching that field, and it must be reported under the skill id or every own tool
    collapses to the single name "Skill". A CLI reaches it as a Bash/PowerShell call with
    the command line in `input.command`, which is invisible to both other matchers; for
    a stack made mostly of CLIs, telemetry would see almost none of it without this.

    Only Bash calls the AGENT MADE are visible. A CLI the human runs in their own
    terminal, or one wired into a pre-commit hook, never enters a transcript - so a zero
    here means "the agent never reached for it", NOT "it was never used". That is the
    whole reason `also_runs_in` and the opportunity matchers exist.
    """
    if name == "Skill" and m.skill:
        sid = (block.get("input") or {}).get("skill")
        if not isinstance(sid, str) or not matches(sid, m.skill):
            return None
        return f"skill:{sid}"
    if name in BASH_TOOLS and m.command:
        cmd = (block.get("input") or {}).get("command")
        if not isinstance(cmd, str):
            return None
        hit = first_match(cmd, m.command)
        return f"cmd:{hit}" if hit is not None else None
    return name if m.tool and matches(name, m.tool) else None


def matcher_needles(m: Matchers) -> set[str]:
    """The literal heads a raw-byte prescan can look for on behalf of `m`."""
    if not m.declared():
        return set()
    return (
        {literal_prefix(g) for g in m.tool}
        | {literal_prefix(g) for g in m.command}
        | ({'"name":"Skill"'} if m.skill else set())
    )


def command_identities(cmd: str) -> list[str]:
    """Everything a command line can be identified BY: executables, plus script names.

    The executables come from cmdscan.py.
    Splitting a command on newlines and pipes reads heredoc bodies and quoted multi-line
    strings as command lines, and cannot follow a runner chain, which loses real ones.
    Resolving the chain avoids both: `uv run ruff check` counts as BOTH uv and ruff, and
    `python -m pytest` counts as pytest.

    A NOTE ON WHAT THIS CANNOT SEE: `powershell -Command "uv run ruff check ."` resolves
    to ["powershell"] and nothing else - the inner command line is a quoted argument and
    stays opaque, as it is for `bash -c`, `cmd /c`, `python -c` and a heredoc body. That
    is conservative in the safe direction (it never invents an invocation, only loses
    one), so every `cmd:` count is a FLOOR.
    How large a floor depends on how often the agent wraps a command in a shell, which
    varies by machine and shell, so it is left to be measured where it matters rather
    than asserted here. tests/test_cmdscan.py pins the behaviour.

    THE GAP THE CHAIN ALONE LEAVES. cmdscan resolves `uv run python tool.py run` to
    ["uv", "python"], which is correct for its question - what did the shell execute -
    and useless for ours, because a `cli` entry that ships as a python script has no
    other name to be measured under. The interpreter is not the tool.

    So the script filename is added as an identity, and only where it cannot be
    mistaken for a mention: the segment's resolved chain must END at python, i.e. the
    interpreter is what ran the file. `ruff check tool.py`, `git add tool.py` and
    `cat tool.py` all resolve to ruff/git/cat and contribute nothing - which is the
    same substring trap resolving the chain exists to avoid, so it is closed here rather
    than trusted.

    Deliberately NOT pushed down into cmdscan: that module answers what the shell
    executed, the same question an invocation table's `exe` column answers (--reconcile),
    and a script name is the radar's own question. A table that does not record script
    names will therefore report reconcile drift on `command` for an entry matched this
    way. That is a true disagreement, correctly reported; the fix belongs in whatever
    writes that table, not in a fudge here.

    A script identity always carries its `.py`, so a bare executable glob can never
    collide with one.
    """
    out: list[str] = []
    for tokens in tokenize(cmd or ""):
        if not tokens:
            continue
        chain = resolve(tokens)
        for n in chain:
            if n not in out:
                out.append(n)
        if not chain or chain[-1] != "python":
            continue
        for t in tokens:
            if t.startswith("-") or not t.lower().endswith(".py"):
                continue
            base = Path(t.replace("\\", "/")).name
            if base and base not in out:
                out.append(base)
            break
    return out


def first_match(cmd: str, globs: list[str]) -> str | None:
    """The identity that matched, or None. One pass, because the scan is the hot loop.

    Which one matched is what the invocation is reported under - `cmd:ruff` rather than
    a generic `cmd` - so asking twice (does it match / which one) resolved the command
    twice, which is the expensive half.
    """
    return next((h for h in command_identities(cmd) if matches(h, globs)), None)


def prescan_hit(path: Path, needles: list[bytes], overlap: int) -> bool:
    """True if any needle appears in the file's raw bytes.

    A whole-file substring scan is roughly two orders of magnitude cheaper than
    json.loads per line, and the vast majority of transcripts never mention a given
    pilot tool at all. Needles are the globs' literal heads, so this is a superset of
    the real matches with one exception: a chain can resolve through `python` without
    the word in the command line, so run_tool does not prescan for a matcher that
    matches `python`.
    """
    try:
        with path.open("rb") as fh:
            tail = b""
            while True:
                buf = fh.read(CHUNK)
                if not buf:
                    return False
                blob = tail + buf
                for n in needles:
                    if n in blob:
                        return True
                tail = blob[-overlap:] if overlap else b""
    except OSError:
        return False


# --------------------------------------------------------------------------- parsing


def parse_ts(raw: str | None) -> dt.datetime | None:
    if not raw:
        return None
    try:
        # Transcripts write ISO-8601 with a Z suffix; fromisoformat accepts it on 3.11+.
        return dt.datetime.fromisoformat(str(raw))
    except ValueError:
        return None


def iter_blocks(rec: dict):
    msg = rec.get("message")
    if not isinstance(msg, dict):
        return
    content = msg.get("content")
    if not isinstance(content, list):
        return
    for b in content:
        if isinstance(b, dict):
            yield b


class Scan(NamedTuple):
    """One file's yield: what was used, what was replayed, and what the chance was."""

    invocations: list[dict]
    malformed: int
    replayed: list[dict]
    opportunities: list[dict]


def scan_file(
    path: Path,
    session_id: str,
    slug: str,
    subagent: bool,
    use: Matchers,
    text_needles: list[str],
    seen_ids: set[str] | None = None,
    opportunity: Matchers = EMPTY,
    opportunity_seen_ids: set[str] | None = None,
) -> Scan:
    """One streaming pass, answering two questions at once.

    Results are matched back to calls by tool_use_id, which is why the pass keeps a
    pending map: a line that mentions no pilot tool is only parsed when it carries a
    tool_use_id we are actually waiting on.

    REPLAYED HISTORY. Resuming or forking a session writes a NEW transcript that
    replays the earlier one, so the same tool_use id exists in two files. Counting both
    is double-counting one event.
    `seen_ids` carries across files, and callers walk files oldest-first, so the first
    occurrence is the one that counts and the later copies are returned separately
    rather than silently dropped.

    Opportunities get their OWN id set. The two questions are independent, and a call
    that happens to satisfy both matcher sets must count once on each side rather than
    be swallowed by whichever ran first - a shared set would silently make `taken_ratio`
    depend on evaluation order.

    Opportunities carry no latency and no error flag: nothing reads them, and pairing
    each with its tool_result would double the pending map for a number that answers a
    different question. They record only where and when the chance existed.
    """
    invocations: list[dict] = []
    replayed: list[dict] = []
    opportunities: list[dict] = []
    by_id: dict[str, dict] = {}
    seen = seen_ids if seen_ids is not None else set()
    opportunity_seen = opportunity_seen_ids if opportunity_seen_ids is not None else set()
    malformed = 0
    try:
        fh = path.open(encoding="utf-8", errors="replace")
    except OSError:
        return Scan([], 0, [], [])
    with fh:
        for line in fh:
            interesting = any(n in line for n in text_needles)
            if not interesting:
                if not by_id or '"tool_use_id"' not in line:
                    continue
                m = TOOL_USE_ID_RE.search(line)
                if not m or m.group(1) not in by_id:
                    continue
            try:
                rec = json.loads(line)
            except (ValueError, TypeError):
                malformed += 1
                continue
            ts = parse_ts(rec.get("timestamp"))
            for b in iter_blocks(rec):
                btype = b.get("type")
                if btype == "tool_use":
                    raw = b.get("name")
                    if not isinstance(raw, str):
                        continue
                    tid = b.get("id")
                    name = matched_name(b, raw, use)
                    if name is not None:
                        inv = {
                            "tool": name,
                            "at": ts.isoformat() if ts else None,
                            "_ts": ts,
                            "session": session_id,
                            "slug": slug,
                            "subagent": subagent,
                            "latency_ms": None,
                            "is_error": None,
                            "resolved": False,
                        }
                        if isinstance(tid, str) and tid in seen:
                            replayed.append(inv)
                        else:
                            if isinstance(tid, str):
                                seen.add(tid)
                                by_id[tid] = inv
                            invocations.append(inv)
                    chance = matched_name(b, raw, opportunity)
                    if chance is not None and not (
                        isinstance(tid, str) and tid in opportunity_seen
                    ):
                        if isinstance(tid, str):
                            opportunity_seen.add(tid)
                        opportunities.append(
                            {
                                "tool": chance,
                                "at": ts.isoformat() if ts else None,
                                "_ts": ts,
                                "session": session_id,
                                "slug": slug,
                                "subagent": subagent,
                            }
                        )
                elif btype == "tool_result":
                    inv = by_id.pop(b.get("tool_use_id"), None)  # type: ignore[arg-type]
                    if inv is None:
                        continue
                    inv["resolved"] = True
                    inv["is_error"] = bool(b.get("is_error"))
                    if ts and inv["_ts"]:
                        delta = (ts - inv["_ts"]).total_seconds() * 1000.0
                        if delta >= 0:
                            inv["latency_ms"] = round(delta, 1)
    return Scan(invocations, malformed, replayed, opportunities)


def discover(projects: Path) -> list[tuple[Path, str, str, bool]]:
    """(path, session_id, slug, is_subagent) for every transcript on disk."""
    out: list[tuple[Path, str, str, bool]] = []
    if not projects.is_dir():
        return out
    for slug_dir in sorted(p for p in projects.iterdir() if p.is_dir()):
        slug = slug_dir.name
        for f in slug_dir.rglob("*.jsonl"):
            rel = f.relative_to(slug_dir).parts
            if len(rel) == 1:
                out.append((f, f.stem, slug, False))
            else:
                # Sidechain transcripts live under the parent session's uuid directory
                # at varying depth (<uuid>/subagents/..., and .../workflows/wf_*/...),
                # so the invocation is attributed to the parent session rather than
                # counted as a session of its own.
                out.append((f, rel[0], slug, True))
    return out


