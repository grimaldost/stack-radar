def run_tool(
    tool: dict,
    args: argparse.Namespace,
    env: dict | None,
    home: Path,
    files: list,
    index_cache: dict,
) -> dict | None:
    """One entry's field report, written to field/<tool>/ and returned.

    None means the entry could not be measured at all (a name that is not an
    identifier, no matcher, no window) - a condition the caller reports as a FAIL.
    Everything softer is a finding inside the document, so a --all run keeps going and
    reports at the end.
    """
    name = str(tool.get("name"))
    # The report directory is named after the entry, so a name with a path separator or
    # a leading dot would choose where the report is written. Checked here because the
    # field report does not run validate(); the rule is validate()'s own.
    if not is_plain_name(name):
        print(f"[FAIL] {name!r}: not a valid entry name ({NAME_RULE}) - no report written")
        return None
    # The report lands in field/<subdir>/, and field/ is TRACKED. A machine-local entry's
    # NAME must not travel, so its report directory is named for its `redact_as`
    # placeholder, not the entry name - otherwise the private name would be written into a
    # tracked path that redaction of the file CONTENT cannot reach, and the gate would
    # fail on a path the engine itself wrote. An entry with no placeholder cannot be
    # placed safely, so it is refused by name here rather than written to field/<name>/.
    # The placeholder is a directory name, so it is held to the entry-name rule too (a
    # separator or `..` in it would choose where the report is written), and it may not
    # contain the name it stands in for (radar_lib.placeholder_error).
    report_subdir = name
    if tool.get("_local"):
        redact_as = str(tool.get("redact_as") or "").strip()
        if not redact_as:
            print(
                f"[FAIL] {name!r}: a machine-local entry (tools.local/) with no `redact_as` "
                "- its name would be written into the tracked field/ path. Declare "
                "`redact_as` so the report directory can carry the placeholder instead"
            )
            return None
        why = placeholder_error(tool, redact_as)
        if why:
            print(
                f"[FAIL] {name!r}: `redact_as` {redact_as!r} is not a valid placeholder "
                f"({why}) - no report written"
            )
            return None
        report_subdir = redact_as
    findings: list[str] = []
    tel = tool.get("telemetry")
    match = args.match or (tel or {}).get("match") or []
    # Own-ring tools are reached through their skills, not through MCP tools, so
    # `match_skill` globs are matched against a Skill call's `input.skill`.
    skill_globs = list(args.match_skill or (tel or {}).get("match_skill") or [])
    # `match_command` globs are matched against the RESOLVED CHAIN of executables a shell
    # command invokes, which is the only way a CLI-artifact tool appears in a transcript
    # at all. Expanded once, here, so the prescan needles, the scan, --reconcile's count
    # of the index and the document's own `match_command` field all use one set.
    #
    # THE EXPANSION IS FOR DECLARED GLOBS ONLY. It exists because a distribution name is
    # not a module name and an ENTRY is written under the distribution name - the name the
    # tool installs and publishes under - so `pre-commit` could not match the module
    # form, which on some machines is the only one. A `--match-command` override is a
    # probe: someone typed a glob to find out what it matches, and silently measuring a
    # second glob they did not type makes the answer unusable for the question they
    # asked. So an override is literal, and --help says so.
    if args.match_command:
        command_globs = list(args.match_command)
    else:
        command_globs = expand_command_globs(list((tel or {}).get("match_command") or []))
    # Surfaces a transcript cannot record: a git hook fires inside `git commit`, a CI
    # job runs on a server. Declaring them does not add invocations - nothing can - it
    # changes what a low count is allowed to conclude.
    also_runs_in = [str(s) for s in ((tel or {}).get("also_runs_in") or [])]
    # OPPORTUNITY. Declared-only - there is no CLI override, because these are a
    # judgement about when the tool would have applied and a probe flag would invite
    # inventing one per run to make a ratio come out.
    opportunity = Matchers(
        list((tel or {}).get("opportunity_match") or []),
        list((tel or {}).get("opportunity_match_skill") or []),
        expand_command_globs(list((tel or {}).get("opportunity_match_command") or [])),
    )
    if not match and not skill_globs and not command_globs:
        print(
            f"[FAIL] {name}: no [telemetry].match - add a [telemetry] block with "
            '`match` (tool-name globs, e.g. "mcp__plugin_x_y__*") and `since` '
            "(YYYY-MM-DD), or pass --match to probe"
        )
        return None

    since_raw = args.since or (tel or {}).get("since")
    if not since_raw:
        print(f"[FAIL] {name}: no --since and no [telemetry].since")
        return None
    try:
        since = dt.date.fromisoformat(str(since_raw))
        until = dt.date.fromisoformat(args.until) if args.until else dt.datetime.now(dt.UTC).date()
    except ValueError as e:
        print(f"[FAIL] {name}: bad date - {e}")
        return None
    if until < since:
        print(f"[FAIL] {name}: --until {until} precedes since {since}")
        return None

    globs = list(match)
    use = Matchers(globs, skill_globs, command_globs)
    # Prescan needles are a SUPERSET filter: a transcript is parsed only if its raw bytes
    # contain one. A command glob's needle is the executable name itself, which appears
    # inside input.command, so the same mechanism finds it.
    #
    # ONE HOLE, a property of resolving chains rather than reading heads: resolution can
    # name an executable the text does not contain - `uv run -m pytest` and `uv run
    # analyse.py` both resolve through "python", which is nowhere in those command lines.
    # So when a command glob matches "python" itself the needles are not a superset,
    # and the prescan is turned off for that entry rather than left to drop
    # real matches.
    #
    # The opportunity matchers' needles go in the same set, because a session that only
    # ever took the OPPORTUNITY - the whole population the ratio is about - contains none
    # of the use needles, and a prescan that filtered on those alone would drop exactly
    # the files the new number needs. The cost is real: more files pass the filter and get
    # parsed, which the `scan` block reports.
    needles = sorted(matcher_needles(use) | matcher_needles(opportunity))
    if any(n == "" for n in needles):
        findings.append(
            f"[WARN] {name}: a matcher has no literal prefix; the byte prescan is "
            "disabled and every transcript in the window is parsed"
        )
        byte_needles: list[bytes] = []
    elif any(fnmatch("python", g) for g in (*use.command, *opportunity.command)):
        findings.append(
            f"[WARN] {name}: a command matcher matches `python`, which a chain can "
            "resolve through without the word in the command line; the byte prescan is "
            "disabled and every transcript in the window is parsed"
        )
        byte_needles = []
        # The same hole applies line by line inside a parsed file, so every line is
        # read there too.
        needles = [""]
    else:
        byte_needles = [n.encode() for n in needles]
    overlap = max((len(n) for n in byte_needles), default=1) - 1

    t0 = time.monotonic()
    # The census depends only on the window, never on the entry, so a --all run over one
    # window computes it once. It is the expensive half: two bounded reads per main
    # transcript, times every transcript on disk, times every tool would be silly.
    key = (since, until)
    if key not in index_cache:
        index_cache[key] = Index(files, since, until)
    index = index_cache[key]
    invocations: list[dict] = []
    replayed: list[dict] = []
    chances: list[dict] = []
    malformed = 0
    n_in_window = len(index.transcripts)
    n_prescan = n_parsed = 0
    # THE CENSUS, and it is the index's alone. Growing it with every session an entry's
    # own invocations touched would make the denominator ENTRY-DEPENDENT: in a --all table
    # each row would divide by a slightly different number, so the column that looks like
    # one census would be several. The extra
    # ids come from sidechain transcripts (subagents, workflows) whose parent session's
    # own transcript is absent or falls outside the window - real use, but not a session
    # of its own, and never a reason to move one row's denominator. Reported separately.
    sessions_in_window: set[str] = set(index.sessions)
    # One id set for the whole scan; index.transcripts is ordered oldest-first, so a
    # tool_use that appears in two files is credited to the file that saw it first.
    seen_ids: set[str] = set()
    opportunity_seen_ids: set[str] = set()

    for t in index.transcripts:
        if byte_needles and not prescan_hit(t.path, byte_needles, overlap):
            continue
        n_prescan += 1
        n_parsed += 1
        got = scan_file(
            t.path,
            t.session,
            t.slug,
            t.subagent,
            use,
            needles,
            seen_ids,
            opportunity,
            opportunity_seen_ids,
        )
        malformed += got.malformed
        invocations.extend(got.invocations)
        replayed.extend(got.replayed)
        chances.extend(got.opportunities)

    if not byte_needles:
        n_prescan = n_in_window

    def dated_in_window(rows: list[dict]) -> list[dict]:
        return [r for r in rows if r["_ts"] is not None and since <= r["_ts"].date() <= until]

    in_window = dated_in_window(invocations)
    replayed_in_window = len(dated_in_window(replayed))
    chances_in_window = dated_in_window(chances)
    for i in in_window:
        i.pop("_ts", None)
    for i in chances_in_window:
        i.pop("_ts", None)
    wall = round(time.monotonic() - t0, 1)

    used_sessions = {i["session"] for i in in_window}
    used_outside_census = used_sessions - sessions_in_window
    resolved = [i for i in in_window if i["resolved"]]
    errors = [i for i in resolved if i["is_error"]]
    lat_all = [i["latency_ms"] for i in in_window if i["latency_ms"] is not None]
    days_with_use = {i["at"][:10] for i in in_window if i["at"]}
    stamps = sorted(i["at"] for i in in_window if i["at"])

    names = sorted({i["tool"] for i in in_window})
    # Ordered on the typed locals rather than by reading the fields back out of the dict.
    # The row holds strings, ints and optional floats, so its value type is a union that
    # has no unary minus - while `len(rows)` is an int right here, and `n` a string.
    counted: list[tuple[int, str, dict]] = []
    for n in names:
        rows = [i for i in in_window if i["tool"] == n]
        lat = [i["latency_ms"] for i in rows if i["latency_ms"] is not None]
        counted.append(
            (
                len(rows),
                n,
                {
                    "tool": n,
                    "invocations": len(rows),
                    "sessions": len({i["session"] for i in rows}),
                    "errors": sum(1 for i in rows if i["is_error"]),
                    "median_ms": med(lat),
                    "p90_ms": pct(lat, 0.9),
                },
            )
        )
    counted.sort(key=lambda item: (-item[0], item[1]))
    per_tool = [row for _count, _name, row in counted]

    slug_counts: dict[str, int] = {}
    for i in in_window:
        slug_counts[i["slug"]] = slug_counts.get(i["slug"], 0) + 1
    slugs = [
        {"slug": s, "invocations": c}
        for s, c in sorted(slug_counts.items(), key=lambda kv: (-kv[1], kv[0]))
    ]

    # Exposure is compared on the leaf name: the mount prefix varies with how the server
    # was mounted - comparing full names would report the whole surface unused after a
    # remount - while the tool surface it exposes does not.
    def leaf(n: str) -> str:
        return n.rsplit("__", 1)[-1]

    declared = (tel or {}).get("exposed")
    used_leaves = {leaf(n) for n in names}
    declared_leaves = {leaf(n) for n in declared} if declared else set()
    exposure = {
        "declared": list(declared) if declared else None,
        "used": sorted(used_leaves),
        "unused": sorted(declared_leaves - used_leaves) if declared else [],
        "undeclared_used": sorted(used_leaves - declared_leaves) if declared else [],
    }

    # ------------------------------------------------------------------- opportunity
    #
    # THE DENOMINATOR USE NEVER HAD. `sessions_with_use / sessions_in_window` divides by
    # every session on the machine, so a tool that applies to one kind of work reads as
    # unused however diligently it is reached for. Zero use has three readings - the work
    # never called for it, it was not mounted, or it was there and nobody thought of it -
    # and the ratio above cannot separate them. The opportunity matchers name calls that
    # mark a session where the tool WOULD have applied, which separates the first reading
    # from the other two. It does not separate the second from the third; nothing here
    # can, and pretending otherwise would be the tidy lie this script exists to remove.
    opportunity_sessions = {i["session"] for i in chances_in_window}
    took_it = opportunity_sessions & used_sessions
    opportunity_names = sorted({i["tool"] for i in chances_in_window})
    opportunity_tools = sorted(
        (
            {
                "tool": n,
                "invocations": sum(1 for i in chances_in_window if i["tool"] == n),
                "sessions": len({i["session"] for i in chances_in_window if i["tool"] == n}),
            }
            for n in opportunity_names
        ),
        key=lambda r: (-r["invocations"], r["tool"]),
    )

    days = (until - since).days + 1
    metrics = {
        "sessions_in_window": len(sessions_in_window),
        # Transcripts whose mtime is in the window while their own records are not: what
        # a denominator dated by mtime would have counted wrongly. Reported rather than
        # silently dropped, so a reader can see how far the two datings differ on this
        # run. TRANSCRIPTS, and the name says so: it counts FILES, which is not the same
        # quantity as the sessions they stand for.
        "transcripts_excluded_by_timestamp": index.transcripts_excluded_by_timestamp,
        # Main transcripts with no parseable timestamp at either end, which are dated by
        # the mtime rule instead. Kept in the census rather than dropped - dropping would
        # shrink the denominator on a parsing failure, which flatters every ratio - and
        # surfaced in the report because a census that rests on the mtime rule for part
        # of its rows should say how large that part is.
        "sessions_dated_by_mtime": index.dated_by_mtime,
        # Matching calls dropped because the same tool_use id had already been counted
        # in an older transcript - a resumed or forked session replays the session it
        # continues.
        "replayed_dropped": replayed_in_window,
        "sessions_with_use": len(used_sessions),
        # Sessions with use that the census does not contain - sidechain-only, or a parent
        # whose main transcript is gone. Reported rather than folded into the denominator,
        # which is what made the denominator entry-dependent.
        "sessions_with_use_outside_census": len(used_outside_census),
        "invocations": len(in_window),
        "invocations_per_used_session": (
            round(len(in_window) / len(used_sessions), 1) if used_sessions else None
        ),
        "resolved": len(resolved),
        "unresolved": len(in_window) - len(resolved),
        "errors": len(errors),
        "error_rate": round(len(errors) / len(resolved), 3) if resolved else None,
        "latency_median_ms": med(lat_all),
        "latency_p90_ms": pct(lat_all, 0.9),
        "days_with_use": len(days_with_use),
        "main_invocations": sum(1 for i in in_window if not i["subagent"]),
        "subagent_invocations": sum(1 for i in in_window if i["subagent"]),
        "first_seen": stamps[0] if stamps else None,
        "last_seen": stamps[-1] if stamps else None,
        # None, not 0, when no opportunity matcher is declared. "0 sessions had an
        # opportunity" is a measurement; "nobody said what an opportunity looks like" is
        # not, and collapsing the two is how a zero comes to read as evidence.
        "opportunity_sessions": len(opportunity_sessions) if opportunity.declared() else None,
        "sessions_with_use_among_opportunity": len(took_it) if opportunity.declared() else None,
        "taken_ratio": (
            round(len(took_it) / len(opportunity_sessions), 3) if opportunity_sessions else None
        ),
        "opportunity_invocations": len(chances_in_window) if opportunity.declared() else None,
        "opportunity_tools": opportunity_tools,
        "per_tool": per_tool,
        "slugs": slugs,
        "exposure": exposure,
    }

    # ------------------------------------------------------------- mechanical checks
    #
    # WHOSE CRITERIA THESE ARE. A [pilot_exit] block survives a demotion on purpose
    # (radar_lib.validate allows it on any entry that WAS a pilot): the criteria were
    # written before the data existed, and deleting them on the way out would let a
    # parked experiment come back with fresh, conveniently looser ones. But surviving is
    # not the same as being under test. Evaluated against the FIRST history entry with
    # ring == pilot whatever the current ring is, the block would keep an entry demoted
    # to observe reporting "pilot review is due" and "min_sessions_with_use NOT met" for
    # an experiment that has already ended. A finding that cannot lead to an action is
    # noise that teaches the reader to skim the findings list.
    px = tool.get("pilot_exit")
    in_pilot = tool.get("ring") == "pilot"
    checks: list[dict] = []
    if px and not in_pilot:
        findings.append(
            f"[NOTE] {name}: [pilot_exit] retained from an earlier pilot and NOT "
            f"evaluated - the entry is at ring={tool.get('ring')!r}. The criteria stay on "
            "the entry as the record of what was promised; they apply again if it is "
            "re-piloted, and re-writing them at that point would be pre-registration "
            "laundering."
        )
    elif px:
        rad = px.get("review_after_days")
        # The LAST pilot entry, not the first: an entry that piloted, was parked and was
        # re-piloted is days into the current experiment, not into the earlier one.
        entered = next(
            (
                h.get("date")
                for h in reversed(tool.get("history") or [])
                if h.get("ring") == "pilot"
            ),
            None,
        )
        if isinstance(rad, int) and entered:
            try:
                age = (dt.date.today() - dt.date.fromisoformat(str(entered))).days
                checks.append(
                    {
                        "check": "review_after_days",
                        "verdict": "DUE" if age >= rad else "not yet",
                        "detail": f"{age}d in pilot since {entered}, review at {rad}d",
                    }
                )
                if age >= rad:
                    findings.append(
                        f"[FLAG] {name}: pilot review is due ({age}d >= {rad}d) - "
                        "a radar session with a human decides the ring, not this script"
                    )
            except ValueError:
                pass
        numeric = {
            "min_sessions_with_use": ("sessions_with_use", "ge"),
            "min_invocations": ("invocations", "ge"),
            "max_error_rate": ("error_rate", "le"),
        }
        for key, (metric, op) in numeric.items():
            if key not in px:
                continue
            want, got = px[key], metrics[metric]
            if got is None:
                verdict, detail = "unevaluated", f"no data for {metric}"
            elif (got >= want) if op == "ge" else (got <= want):
                verdict, detail = "met", f"{metric}={got} vs {key}={want}"
            else:
                verdict, detail = "NOT met", f"{metric}={got} vs {key}={want}"
            checks.append({"check": key, "verdict": verdict, "detail": detail})
            if verdict == "NOT met":
                findings.append(f"[NOTE] {name}: pre-registered {key} not met - {detail}")
    elif in_pilot:
        # Only a pilot owes exit criteria, which is the gate's rule too. Warning on every
        # own/adopt entry printed one line per entry that no action could follow, and
        # buried the warnings that could.
        findings.append(
            f"[WARN] {name}: no [pilot_exit] block - nothing to check the field "
            "data against; criteria written after the data are not criteria"
        )

    # -------------------------------------------------------------------- findings
    if not in_window:
        # THREE READINGS, and the count above tells them apart from none of the others.
        # Naming only two ("not mounted, or the work never called for it") would quietly
        # exclude the third: the tool was there, the work fitted, and the agent never
        # reached for it. A ring is not moved on a zero whose cause is
        # unknown, so the reading the report omits is the reading nobody argues about.
        parts = [
            f"[NOTE] {name}: zero measured use - {len(sessions_in_window)} sessions in "
            "the window, none invoked a matching tool. Not an error: it is the finding. "
            "It has three readings and these counts separate none of them on their own - "
            "(1) the work never called for it, (2) it was not mounted or reachable, "
            "(3) it was there and applicable and was never reached for."
        ]
        # also_runs_in belongs here as much as in the thin-surface branch below, and was
        # consulted only there: an entry that runs entirely inside git hooks or CI reads
        # ZERO here, which is the strongest possible version of the same false conclusion.
        if also_runs_in:
            parts.append(
                "The entry declares surfaces no transcript records - "
                f"{', '.join(also_runs_in)} - so reading (2) is already excluded and the "
                "zero measures reach, not use."
            )
        if opportunity.declared():
            parts.append(
                f"{len(opportunity_sessions)} session(s) had an opportunity by the "
                f"entry's own opportunity matchers, {len(took_it)} took it - so reading "
                "(1) is settled and what remains is (2) against (3)."
                if opportunity_sessions
                else "The entry declares opportunity matchers and 0 session(s) matched "
                "them, which points at reading (1): the occasion never arose."
            )
        findings.append(" ".join(parts))
    else:
        used_frac = len(used_sessions) / max(1, len(sessions_in_window))
        if used_frac < 0.05:
            rate = (
                f"used in {len(used_sessions)}/{len(sessions_in_window)} sessions ({used_frac:.1%})"
            )
            # A FLAG here is false by construction for anything that runs where a
            # transcript cannot see it. A pre-commit hook that fires on every commit
            # still reads as a handful of sessions, because only the agent's own calls
            # are recorded - the number is right and the conclusion drawn from it would
            # be backwards. Where the entry declares the invisible surfaces, the finding
            # says what the count is missing instead of pretending the count is the whole
            # picture.
            if also_runs_in:
                findings.append(
                    f"[NOTE] {name}: {rate}, but this counts only what the AGENT "
                    f"reached for. The entry declares that it also runs in: "
                    f"{', '.join(also_runs_in)} - surfaces no transcript records. Read "
                    "the ratio as reach-frequency, not as adoption."
                )
            else:
                findings.append(
                    f"[FLAG] {name}: thin opportunity surface - {rate}; "
                    "an effect this rare cannot pay for its context cost"
                )
        if metrics["error_rate"] is not None and metrics["error_rate"] > 0.1:
            findings.append(
                f"[WARN] {name}: error rate {metrics['error_rate']:.1%} over "
                f"{len(resolved)} resolved calls"
            )
        if metrics["unresolved"]:
            findings.append(
                f"[NOTE] {name}: {metrics['unresolved']} call(s) have no matching "
                "tool_result in the transcript (interrupted, or the result is in a file "
                "outside the window); their latency is unknown"
            )
    if used_outside_census:
        findings.append(
            f"[NOTE] {name}: {len(used_outside_census)} session(s) with use are not in "
            "the window census - the calls come from sidechain transcripts (subagents, "
            "workflows) whose parent session's own transcript is absent or falls outside "
            "the window. They count in the numerator and deliberately NOT in the "
            "denominator: the denominator is one census shared by every entry, so that a "
            "--all table's rows divide by the same number."
        )
    if malformed:
        findings.append(f"[NOTE] {name}: {malformed} unparseable transcript line(s) skipped")
    if days < 7:
        findings.append(
            f"[WARN] {name}: the window is {days} day{'' if days == 1 else 's'} - "
            "too short for an opportunity-frequency census; widen --since before reading "
            "the sessions-with-use ratio as anything"
        )
    # RETENTION, which is the difference between "nothing happened" and "the evidence is
    # gone". Claude Code prunes transcripts after a configurable retention period, so a
    # window that starts before the oldest surviving transcript has a TRUNCATED
    # denominator and a truncated numerator, and neither is visible in the numbers.
    oldest = index.oldest_record_by_head_scan
    if oldest is not None and oldest > since:
        findings.append(
            f"[WARN] {name}: the census is truncated by retention - the oldest record a "
            f"BOUNDED HEAD SCAN finds on disk is {oldest}, after --since {since}. "
            f"Everything before that was pruned, so both the denominator and the counts "
            f"cover {oldest}..{until}, not the window asked for. The date is a CEILING, "
            "not the edge: only each transcript's first 64 KiB is read, so history "
            "replayed deeper into a resumed session is not seen and the true oldest "
            "record can be earlier."
        )

    # ------------------------------------------------------------------- reconcile
    reconcile: dict | None = None
    if args.reconcile:
        store_raw = ((env or {}).get("paths") or {}).get("transcript_index")
        store = Path(str(store_raw).replace("\\", "/")) if store_raw else None
        loaded = load_transcript_index(store) if store else None
        if store is None:
            findings.append(
                f"[NOTE] {name}: --reconcile asked for, but the {args.env!r} profile "
                "declares no [paths].transcript_index - nothing to cross-check against"
            )
        elif loaded is None:
            findings.append(
                f"[NOTE] {name}: --reconcile asked for, but no derived table at "
                f"{store / 'derived' / 'invocations.jsonl'} - the table has never been "
                "derived here, or the path is wrong"
            )
        else:
            rows, generated_at = loaded
            cutoff = utc_moment(generated_at)
            theirs = index_counts(rows, since, until, globs, skill_globs, command_globs, cutoff)
            ours = our_counts(in_window, command_globs, cutoff)
            if cutoff is not None and cutoff.date() < since:
                findings.append(
                    f"[NOTE] {name}: the invocation table was derived {generated_at}, "
                    f"before the window starts ({since}) - there is nothing to compare "
                    "until it is derived again"
                )
            declared = {
                "command": bool(command_globs),
                "skill": bool(skill_globs),
                "mcp": bool(globs),
            }
            age = derive_age_hours(generated_at)
            kinds = []
            for kind in RECONCILE_KINDS:
                if not declared[kind]:
                    continue
                a, b = ours[kind], theirs[kind]
                rel = abs(a - b) / max(a, b) if max(a, b) else 0.0
                # Every declared kind is compared (see SCRIPT NAMES above
                # RECONCILE_KINDS); `comparable` is part of the report's shape.
                comparable = True
                kinds.append(
                    {
                        "kind": kind,
                        "ours": a,
                        "index": b,
                        "delta": a - b,
                        "relative": round(rel, 4),
                        "comparable": comparable,
                    }
                )
                if comparable and rel > RECONCILE_TOLERANCE:
                    findings.append(
                        f"[WARN] {name}: reconcile drift on `{kind}` - ours {a}, "
                        f"index {b} ({rel:.1%} apart, tolerance "
                        f"{RECONCILE_TOLERANCE:.0%}). Either the two scanners disagree, "
                        f"or the index is stale (derived "
                        f"{generated_at or 'at an unknown time'}"
                        + (f", {age}h ago" if age is not None else "")
                        + ") - check the age before the code."
                    )
            reconcile = {
                "store": str(store),
                "generated_at": generated_at,
                "age_hours": age,
                # `age_hours` is the value to read; `age_days` is derived from it, for a
                # reader who wants the coarser unit without recomputing it.
                "age_days": int(age // 24) if age is not None else None,
                "compared_up_to": generated_at if cutoff is not None else None,
                "tolerance": RECONCILE_TOLERANCE,
                "kinds": kinds,
            }

    doc = {
        "generated_by": "radar field",
        "generated_at": dt.datetime.now(dt.UTC).isoformat(timespec="seconds"),
        "descriptive_only": DESCRIPTIVE_BANNER,
        "tool": name,
        "ring": tool.get("ring"),
        "environment": args.env,
        "claude_home": str(home),
        "match": globs,
        "match_skill": skill_globs,
        "match_command": command_globs,
        "opportunity_match": opportunity.tool,
        "opportunity_match_skill": opportunity.skill,
        "opportunity_match_command": opportunity.command,
        "also_runs_in": also_runs_in,
        "match_override": bool(args.match),
        "window": {
            "since": since.isoformat(),
            "until": until.isoformat(),
            "days": days,
        },
        "scan": {
            "transcripts_on_disk": len(files),
            "in_time_window": n_in_window,
            "prescan_hits": n_prescan,
            "parsed": n_parsed,
            "malformed_lines": malformed,
            "wall_clock_s": wall,
            # The field name carries the caveat because the value cannot: it is the
            # earliest timestamp in any main transcript's first 64 KiB, which is a
            # CEILING on how far back the evidence reaches, not the edge itself.
            "oldest_record_by_head_scan": (
                index.oldest_record_by_head_scan.isoformat()
                if index.oldest_record_by_head_scan
                else None
            ),
        },
        "metrics": metrics,
        "reconcile": reconcile,
        "pilot_exit": px,
        "pilot_exit_evaluated": bool(px) and in_pilot,
        "checks": checks,
        "findings": findings,
        # The raw call list is the audit trail behind the aggregates. It is capped so a
        # busy tool's report stays a document rather than a data dump; the aggregates
        # above are always complete.
        "invocations_recorded": min(len(in_window), RAW_CAP),
        "invocations_truncated": len(in_window) > RAW_CAP,
        "invocations": in_window[:RAW_CAP],
    }

    # Under the data root unless --out-dir names another place. A destination inside the
    # data root, field/ or an --out-dir spelled under it, is written only through
    # write_inside, which refuses a symbolic link on the way.
    data_root = field_dir().parent
    out_dir = (Path(args.out_dir) if args.out_dir else field_dir()) / report_subdir
    inside_root = (
        data_root
        if Path(os.path.abspath(out_dir)).is_relative_to(os.path.abspath(data_root))
        else None
    )
    # A --match run measures something other than what the entry declares, so it must
    # not be able to overwrite the entry's real field record.
    stem = f"{since.isoformat()}_{until.isoformat()}" + ("-probe" if args.match else "")
    md_path, json_path = out_dir / f"{stem}.md", out_dir / f"{stem}.json"
    # field/ is TRACKED, and a session slug is derived from the project path the
    # session ran in - so a report can carry a project's name through its slugs without a
    # word of prose mentioning it. This is post-hoc mining of paths we do not control, so
    # it cannot be fixed at the source: it is mapped out on the way to disk. Only the
    # written artefacts are redacted - `--json` to stdout keeps the real names, because
    # whoever runs it is on the machine that owns them.
    #
    # The same slug carries the home directory, and so do `claude_home` and the index
    # location: every report would name the machine's account. The home goes first, so a
    # scoped term can never split a home path and leave the rest of it behind. The homes
    # declared in `redact.local.toml` go with it: sessions synced from another machine
    # keep that machine's slugs, and this is the one writer that meets them.
    _terms, _homes = scoped_terms(), [home_dir(), *extra_homes()]

    def _redact(text: str) -> str:
        return redact_text(redact_homes(text, _homes), _terms)

    # The Markdown escapes transcript-derived values (a backslash is doubled, a tag's
    # brackets become entities), and a home or a scoped term spelled inside an escaped
    # value would no longer match its redaction pattern. So the values are redacted
    # first, through their JSON spelling, and the rendered text once more.
    shown = json.loads(_redact(json.dumps(doc)))
    # LF on every OS, like every tracked file the engine writes: CRLF would show each
    # report as modified on Windows until it is staged.
    written = {
        md_path: _redact(render_md(shown)),
        json_path: _redact(json.dumps(doc, indent=2) + "\n"),
    }
    if inside_root is not None:
        # Both files are judged before either is written, so a refusal leaves no half.
        refused = [e for e in (write_error(inside_root, p) for p in written) if e]
        if refused:
            for err in refused:
                print(f"[FAIL] {name}: {err} - the report was not written")
            raise SystemExit(1)
    for path, text in written.items():
        if inside_root is None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        else:
            write_inside(inside_root, path, text)
    doc["_paths"] = {"md": str(md_path), "json": str(json_path)}
    doc["_scan_line"] = (
        f"scanned {n_parsed}/{n_in_window} of {len(files)} transcripts in {wall}s "
        f"({DESCRIPTIVE_BANNER.split(' - ')[0]})"
    )
    return doc


def print_report(doc: dict) -> None:
    """The single-tool console read-out."""
    m, w = doc["metrics"], doc["window"]
    for f in doc["findings"]:
        print(f)
    print(
        f"\n{doc['tool']}: {m['invocations']} invocations, "
        f"{m['sessions_with_use']}/{m['sessions_in_window']} sessions with use, "
        f"{len(m['per_tool'])} distinct tools, window {w['since']}..{w['until']}"
    )
    print(doc["_scan_line"])
    for line in reconcile_lines(doc["tool"], doc.get("reconcile")):
        print(line)
    print(f"wrote {doc['_paths']['md']}")
    print(f"wrote {doc['_paths']['json']}")


# ONE LINE FOR A SCHEDULED REVIEW. Running one tool at a time is how a declared matcher
# goes a month without ever being run, and a matcher that is never run is not a deferred
# measurement - the transcripts it needed get pruned. --all makes the whole board one
# command.
INACTIVE_RINGS = ("observe", "discard")
SUMMARY_HEADER = ("tool", "ring", "inv", "sessions", "err", "findings")


def selected_tools(tools: list[dict], include_inactive: bool) -> list[dict]:
    """Entries with a declared matcher, in name order. Inactive rings dropped by default.

    An observe/discard entry claims nothing, so there is nothing about it to check - and
    running the lot on every scheduled review would bury the entries whose rings ARE
    claims. Pass --include-inactive when the question is about a demoted entry
    specifically.
    """
    out = []
    for t in sorted(tools, key=lambda t: str(t.get("name") or "")):
        tel = t.get("telemetry") or {}
        if not any(tel.get(k) for k in MATCHER_KEYS):
            continue
        if not include_inactive and t.get("ring") in INACTIVE_RINGS:
            continue
        out.append(t)
    return out


def summary_table(rows: list[list[str]]) -> list[str]:
    widths = [max(len(str(r[i])) for r in [list(SUMMARY_HEADER), *rows]) for i in range(6)]
    fmt = "  ".join(f"{{:<{w}}}" for w in widths)
    out = [fmt.format(*SUMMARY_HEADER), fmt.format(*("-" * w for w in widths))]
    out += [fmt.format(*r) for r in rows]
    return out


@reports_profile_errors
def main() -> None:
    args = build_parser().parse_args()
    # The banner goes to stderr, which is what keeps `--json` a parseable document.
    root = begin_command(args.data_root)
    args.env = args.env or default_environment(root)
    if bool(args.tool) == bool(args.all):
        print("[FAIL] name one tool, or pass --all - not both, not neither")
        sys.exit(2)
    if args.all and args.json:
        # There is no defined single document for one report per entry, and silently
        # ignoring the flag would hand a script an empty parse instead of an error.
        # Each entry's JSON is on disk under field/<tool>/ either way.
        print("[FAIL] --json reports one tool; with --all, read field/<tool>/*.json")
        sys.exit(2)

    tools = load_tools()
    env = load_environment(args.env)
    if env is None and not args.claude_home:
        print(f"[FAIL] no environment named {args.env!r} and no --claude-home")
        sys.exit(1)
    home = Path(args.claude_home or (env or {}).get("paths", {}).get("claude_home", ""))
    projects = home / "projects"
    if not projects.is_dir():
        print(f"[FAIL] no transcript directory at {projects}")
        sys.exit(1)
    files = discover(projects)
    index_cache: dict = {}

    if not args.all:
        tool = next((t for t in tools if t.get("name") == args.tool), None)
        if tool is None:
            print(f"[FAIL] {args.tool}: no tools/*.toml entry with this name")
            sys.exit(1)
        doc = run_tool(tool, args, env, home, files, index_cache)
        if doc is None:
            sys.exit(1)
        if args.json:
            print(json.dumps({k: v for k, v in doc.items() if not k.startswith("_")}, indent=2))
        else:
            print_report(doc)
        sys.exit(1 if any(f.startswith("[FAIL]") for f in doc["findings"]) else 0)

    selected = selected_tools(tools, args.include_inactive)
    if not selected:
        print("[FAIL] --all selected no entry - does any tools/*.toml declare a matcher?")
        sys.exit(1)
    rows: list[list[str]] = []
    fails = 0
    for tool in selected:
        doc = run_tool(tool, args, env, home, files, index_cache)
        if doc is None:
            fails += 1
            rows.append([str(tool.get("name")), str(tool.get("ring")), "-", "-", "-", "FAIL"])
            continue
        m = doc["metrics"]
        for f in doc["findings"]:
            print(f)
        for line in reconcile_lines(doc["tool"], doc.get("reconcile")):
            print(line)
        fails += sum(1 for f in doc["findings"] if f.startswith("[FAIL]"))
        rows.append(
            [
                doc["tool"],
                str(doc["ring"]),
                str(m["invocations"]),
                f"{m['sessions_with_use']}/{m['sessions_in_window']}",
                str(m["errors"]),
                str(len(doc["findings"])),
            ]
        )
    print()
    for line in summary_table(rows):
        print(line)
    # Without --since each entry uses its own [telemetry].since, so there is no single
    # window to name and claiming one would be the kind of tidy lie this script exists
    # to remove.
    window = (
        f"{args.since}..{args.until or dt.datetime.now(dt.UTC).date()}"
        if args.since
        else "per-entry [telemetry].since"
    )
    print(
        f"\n{len(selected)} entr{'y' if len(selected) == 1 else 'ies'} with a matcher, "
        f"window {window} - {fails} FAIL"
    )
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
